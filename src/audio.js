// Audio engine for the SpyMouse web port.
//
// Native reference (see analysis/rea/audio/findings.md):
//   0x132BA0 playSound(id, loopFlag, priority)  - id 0..176 from the 177-entry table @0x2BA3EC
//   0x132680 stopSound(id)
//   0x1327C8 active-voice list, max 8 voices, lowest priority is stolen
//   0x7CD98  playMusic(path) with a separate 0..1 music volume
//
// Constraints from the implementation contract:
//   - the module top level must never touch window/Audio/AudioContext (Node smoke imports it)
//   - every public method is a safe no-op when uninitialised / unloaded / locked
//
// Manifest shape (generated by tools/transcode-sps.ps1):
//   { version: 1, generated: '...',
//     sfx:   { "113": { file, loop, loopStart, loopEnd, duration, sampleRate, category } },
//     music: { "CM_Menu1": { file, loop, loopStart, loopEnd, duration, sampleRate } } }

const MAX_VOICES = 8;
const DEDUPE_SECONDS = 0.03;
const MANIFEST_PATH = '../assets/audio/manifest.json';

function clamp01(n, fallback) {
  const v = Number(n);
  if (!Number.isFinite(v)) return fallback;
  return Math.max(0, Math.min(1, v));
}

export class AudioEngine {
  constructor() {
    this.ctx = null;
    this.manifest = null;
    this.master = null;
    this.musicBus = null;
    this.effectsBus = null;
    this.settings = { music: 0.55, effects: 0.8 };
    this.voices = [];            // { id, source, gain, priority, loop, startedAt }
    this.musicName = null;
    this.musicSource = null;
    this.musicGain = null;
    this.objectLoops = new Map(); // objId -> id (native 0xA76E0 / 0xB1588)
    this.buffers = new Map();     // file -> Promise<AudioBuffer|null>
    this.failedFiles = new Set();
    this.lastPlayedAt = new Map();
    this.stopEpoch = new Map();   // id -> counter; cancels sounds still loading when stopSound() is called
    // playMusic() may be called by Game/FrontEnd before the async init() has
    // resolved; remember the last request and start it once ready.
    this._pendingMusic = null;    // { name, opts }
    this._initPromise = null;
    this._manifestTried = false;
  }

  /** True once the manifest is loaded and an AudioContext exists. */
  get ready() {
    return !!(this.manifest && this.ctx);
  }

  /**
   * Load the manifest and (browser only) lazily create the AudioContext.
   * Safe to call in Node / before a user gesture: it just returns this.
   */
  async init(settings = {}) {
    this.setVolumes(settings);
    if (this._initPromise) return this._initPromise;
    this._initPromise = (async () => {
      if (typeof window === 'undefined' || typeof fetch !== 'function') return this;
      try {
        const url = new URL(MANIFEST_PATH, import.meta.url);
        const res = await fetch(url.href, { cache: 'no-cache' });
        if (!res.ok) return this;
        const data = await res.json();
        if (!data || typeof data !== 'object') return this;
        this.manifest = data;
        this._createContext();
        this._preloadCore();
        this._flushPendingMusic();
      } catch {
        // no manifest yet / file:// / blocked: stay silent, playSound is a no-op
      }
      this._manifestTried = true;
      return this;
    })();
    return this._initPromise;
  }

  setVolumes({ music = 0.55, effects = 0.8 } = {}) {
    this.settings = { music: clamp01(music, 0.55), effects: clamp01(effects, 0.8) };
    if (this.musicBus) this.musicBus.gain.value = this.settings.music;
    if (this.effectsBus) this.effectsBus.gain.value = this.settings.effects;
  }

  /** Must be called from a user gesture (click/keydown) on mobile browsers. */
  async unlock() {
    this._createContext();
    if (!this.ctx) return;
    try {
      if (this.ctx.state !== 'running') await this.ctx.resume();
    } catch {
      /* ignored */
    }
    // Some browsers only allow audio after a gesture; retry a music request
    // that arrived before init()/unlock().
    this._flushPendingMusic();
  }

  /**
   * Play a sound effect by native id (0..176).
   * Missing id / manifest / buffer or no AudioContext => silent no-op.
   */
  playSound(id, { loop = false, priority = 5, volume = 1 } = {}) {
    try {
      if (!this.ctx || !this.manifest) return;
      const key = String(id);
      const entry = this.manifest.sfx && this.manifest.sfx[key];
      if (!entry || !entry.file) return;
      const now = this.ctx.currentTime;
      const lastName = this.lastPlayedAt.get(key);
      if (!loop && lastName != null && now - lastName < DEDUPE_SECONDS) return;
      this.lastPlayedAt.set(key, now);

      const prio = Number.isFinite(Number(priority)) ? Number(priority) : 5;
      this._trimVoices(prio);
      if (this._voiceCount() >= MAX_VOICES) return;

      const vol = clamp01(volume, 1);
      const epoch = this.stopEpoch.get(key) || 0;
      this._getBuffer(entry.file).then((buffer) => {
        if (!buffer || !this.ctx) return;
        if ((this.stopEpoch.get(key) || 0) !== epoch) return; // stopSound() raced the load
        const source = this.ctx.createBufferSource();
        source.buffer = buffer;
        source.loop = !!loop;
        const gain = this.ctx.createGain();
        gain.gain.value = vol;
        source.connect(gain);
        gain.connect(this.effectsBus || this.ctx.destination);
        const voice = { id: key, source, gain, priority: prio, loop: !!loop, startedAt: this.ctx.currentTime };
        source.onended = () => {
          const i = this.voices.indexOf(voice);
          if (i >= 0) this.voices.splice(i, 1);
          try { source.disconnect(); gain.disconnect(); } catch { /* ignored */ }
        };
        this.voices.push(voice);
        try { source.start(); } catch { /* ignored */ }
      }).catch(() => {});
    } catch {
      /* audio must never break gameplay */
    }
  }

  /** Stop every active voice of this id (native 0x132680). */
  stopSound(id) {
    const key = String(id);
    this.stopEpoch.set(key, (this.stopEpoch.get(key) || 0) + 1);
    for (const voice of [...this.voices]) {
      if (voice.id !== key) continue;
      this._stopVoice(voice, 0.01);
    }
    this.objectLoops.forEach((value, objId) => {
      if (value === key) this.objectLoops.delete(objId);
    });
  }

  /**
   * Start a music track from the manifest, e.g. 'CM_Apartments' or 'CM_Menu1'.
   * Accepts 'sound/music/CM_Menu1.sps' too. Replaces the current track.
   * Returns true when the request was accepted (started or already playing);
   * before init()/unlock() the last request is queued instead of being dropped.
   */
  playMusic(name, { loop = true, volume = 1, fade = 0.3 } = {}) {
    try {
      if (!this.ctx || !this.manifest) {
        // Game/FrontEnd may call this before the async init() resolved; keep
        // only the newest request and retry from init()/unlock().
        this._pendingMusic = { name, opts: { loop, volume, fade } };
        return false;
      }
      const key = this._musicKey(name);
      if (!key) return false;
      const entry = this.manifest.music && this.manifest.music[key];
      if (!entry || !entry.file) return false;
      if (this.musicName === key && this.musicSource) return true;

      this.stopMusic(fade);
      const token = (this._musicToken = (this._musicToken || 0) + 1);
      this.musicName = key;
      const vol = clamp01(volume, 1);
      const fadeSec = Math.max(0, Number(fade) || 0);

      this._getBuffer(entry.file).then((buffer) => {
        if (!buffer || !this.ctx || token !== this._musicToken) return;
        const source = this.ctx.createBufferSource();
        source.buffer = buffer;
        const wantsLoop = !!loop && entry.loop !== false;
        source.loop = wantsLoop;
        if (wantsLoop) {
          const rate = entry.sampleRate || 22050;
          if (entry.loopStart != null) source.loopStart = entry.loopStart / rate;
          if (entry.loopEnd != null) source.loopEnd = entry.loopEnd / rate;
        }
        const gain = this.ctx.createGain();
        gain.gain.value = 0;
        source.connect(gain);
        gain.connect(this.musicBus || this.ctx.destination);
        this.musicSource = source;
        this.musicGain = gain;
        const target = vol * this.settings.music;
        const now = this.ctx.currentTime;
        if (fadeSec > 0) {
          gain.gain.setValueAtTime(0, now);
          gain.gain.linearRampToValueAtTime(target, now + fadeSec);
        } else {
          gain.gain.setValueAtTime(target, now);
        }
        source.onended = () => {
          if (this.musicSource === source) {
            this.musicSource = null;
            this.musicGain = null;
            this.musicName = null;
          }
          try { source.disconnect(); gain.disconnect(); } catch { /* ignored */ }
        };
        try { source.start(); } catch { /* ignored */ }
      }).catch(() => {});
      return true;
    } catch {
      return false;
    }
  }

  /** Start a playMusic() request that arrived before init()/unlock() was ready. */
  _flushPendingMusic() {
    const pending = this._pendingMusic;
    if (!pending) return;
    if (!this.ctx || !this.manifest) return;
    // Unknown tracks are dropped instead of retried forever.
    const key = this._musicKey(pending.name);
    if (!key || !this.manifest.music || !this.manifest.music[key]) {
      this._pendingMusic = null;
      return;
    }
    this._pendingMusic = null;
    if (!this.playMusic(pending.name, pending.opts)) {
      this._pendingMusic = pending; // keep until a later unlock()/init()
    }
  }

  stopMusic(fade = 0.3) {
    this._pendingMusic = null;
    const source = this.musicSource;
    const gain = this.musicGain;
    this._musicToken = (this._musicToken || 0) + 1;
    this.musicSource = null;
    this.musicGain = null;
    this.musicName = null;
    if (!source) return;
    try {
      const now = this.ctx ? this.ctx.currentTime : 0;
      const fadeSec = Math.max(0, Number(fade) || 0);
      if (gain) {
        gain.gain.cancelScheduledValues(now);
        gain.gain.setValueAtTime(gain.gain.value, now);
        gain.gain.linearRampToValueAtTime(0, now + fadeSec);
      }
      source.stop(now + fadeSec + 0.02);
    } catch {
      /* ignored */
    }
  }

  /**
   * Per-object looping sound, mirroring native 0xA76E0 (objects) / 0xB1588 (player).
   * Starting a new id stops the previous loop of that object.
   */
  setObjectLoop(objId, id) {
    const key = objId == null ? null : String(objId);
    if (key == null) return;
    const next = id == null ? null : String(id);
    const prev = this.objectLoops.get(key) || null;
    if (prev === next) return;
    if (prev != null) this.stopSound(prev);
    if (next == null) {
      this.objectLoops.delete(key);
      return;
    }
    this.objectLoops.set(key, next);
    this.playSound(next, { loop: true });
  }

  // ---- internals -------------------------------------------------------

  _createContext() {
    if (this.ctx) return this.ctx;
    const Ctx = (typeof window !== 'undefined')
      ? (window.AudioContext || window.webkitAudioContext)
      : null;
    if (!Ctx) return null;
    try {
      this.ctx = new Ctx();
      this.master = this.ctx.createGain();
      this.master.gain.value = 1;
      this.musicBus = this.ctx.createGain();
      this.effectsBus = this.ctx.createGain();
      this.musicBus.gain.value = this.settings.music;
      this.effectsBus.gain.value = this.settings.effects;
      this.musicBus.connect(this.master);
      this.effectsBus.connect(this.master);
      this.master.connect(this.ctx.destination);
    } catch {
      this.ctx = null;
      this.master = null;
      this.musicBus = null;
      this.effectsBus = null;
    }
    return this.ctx;
  }

  _musicKey(name) {
    if (!name) return null;
    const base = String(name).split(/[\\/]/).pop().replace(/\.sps$/i, '').replace(/\.ogg$/i, '');
    if (this.manifest && this.manifest.music && this.manifest.music[base]) return base;
    if (this.manifest && this.manifest.music && this.manifest.music[name]) return String(name);
    return base || null;
  }

  _getBuffer(file) {
    if (!this.ctx || !file || this.failedFiles.has(file)) return Promise.resolve(null);
    if (this.buffers.has(file)) return this.buffers.get(file);
    const promise = (async () => {
      try {
        const url = new URL('../' + String(file).replace(/^\/+/, ''), import.meta.url);
        const res = await fetch(url.href);
        if (!res.ok) throw new Error('http ' + res.status);
        const bytes = await res.arrayBuffer();
        return await new Promise((resolve, reject) => {
          // decodeAudioData callback form for older Safari
          try {
            const p = this.ctx.decodeAudioData(bytes, resolve, reject);
            if (p && typeof p.then === 'function') p.then(resolve, reject);
          } catch (err) {
            reject(err);
          }
        });
      } catch {
        this.failedFiles.add(file);
        return null;
      }
    })();
    this.buffers.set(file, promise);
    return promise;
  }

  _preloadCore() {
    // Small set used on the very first interactions; everything else loads on demand.
    ['1', '110', '113', '39', '40', '77', '96', '140'].forEach((id) => {
      const entry = this.manifest && this.manifest.sfx && this.manifest.sfx[id];
      if (entry && entry.file) this._getBuffer(entry.file);
    });
  }

  _voiceCount() {
    return this.voices.length;
  }

  _trimVoices(priority) {
    while (this.voices.length >= MAX_VOICES) {
      let victim = null;
      for (const voice of this.voices) {
        if (!victim || voice.priority < victim.priority) victim = voice;
      }
      if (!victim) return;
      if (priority < victim.priority) return; // refuse to steal a more important voice
      this._stopVoice(victim, 0.005);
    }
  }

  _stopVoice(voice, fadeSec = 0.01) {
    const i = this.voices.indexOf(voice);
    if (i >= 0) this.voices.splice(i, 1);
    try {
      const now = this.ctx ? this.ctx.currentTime : 0;
      const fade = Math.max(0, Number(fadeSec) || 0);
      if (voice.gain) {
        voice.gain.gain.cancelScheduledValues(now);
        voice.gain.gain.setValueAtTime(voice.gain.gain.value, now);
        voice.gain.gain.linearRampToValueAtTime(0, now + fade);
      }
      if (voice.source) voice.source.stop(now + fade + 0.01);
    } catch {
      /* ignored */
    }
  }
}

// Shared singleton: importers only ever use this instance.
export const audio = new AudioEngine();
export default audio;
